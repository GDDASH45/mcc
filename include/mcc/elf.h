#ifndef MCC_ELF_H
#define MCC_ELF_H

#include <stdint.h>

#include <mcc/target.h>

#define MCC_ELFCLASS32 1
#define MCC_ELFCLASS64 2
#define MCC_ELFDATA2LSB 1
#define MCC_ELF_VERSION 1
#define MCC_ET_EXEC 2
#define MCC_EM_386 3
#define MCC_EM_X86_64 62
#define MCC_PT_LOAD 1
#define MCC_PF_X 1
#define MCC_PF_W 2
#define MCC_PF_R 4

struct mcc_elf32_ehdr {
    unsigned char e_ident[16];
    uint16_t e_type;
    uint16_t e_machine;
    uint32_t e_version;
    uint32_t e_entry;
    uint32_t e_phoff;
    uint32_t e_shoff;
    uint32_t e_flags;
    uint16_t e_ehsize;
    uint16_t e_phentsize;
    uint16_t e_phnum;
    uint16_t e_shentsize;
    uint16_t e_shnum;
    uint16_t e_shstrndx;
};

struct mcc_elf32_phdr {
    uint32_t p_type;
    uint32_t p_offset;
    uint32_t p_vaddr;
    uint32_t p_paddr;
    uint32_t p_filesz;
    uint32_t p_memsz;
    uint32_t p_flags;
    uint32_t p_align;
};

struct mcc_elf64_ehdr {
    unsigned char e_ident[16];
    uint16_t e_type;
    uint16_t e_machine;
    uint32_t e_version;
    uint64_t e_entry;
    uint64_t e_phoff;
    uint64_t e_shoff;
    uint32_t e_flags;
    uint16_t e_ehsize;
    uint16_t e_phentsize;
    uint16_t e_phnum;
    uint16_t e_shentsize;
    uint16_t e_shnum;
    uint16_t e_shstrndx;
};

struct mcc_elf64_phdr {
    uint32_t p_type;
    uint32_t p_flags;
    uint64_t p_offset;
    uint64_t p_vaddr;
    uint64_t p_paddr;
    uint64_t p_filesz;
    uint64_t p_memsz;
    uint64_t p_align;
};

int mcc_elf_write_executable(const char *path, enum mcc_arch arch);

#endif
